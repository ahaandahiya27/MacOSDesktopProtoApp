#!/usr/bin/env python3
"""P1-C — add `bossQuestions: [Question]` arrays to every Maths chapter.

The Maths pack (`maths_class7.json`, NEP Ganita Prakash Grade 7) shipped with
zero bossQuestions. Boss questions are the high-difficulty pool the v6 adaptive
journey (Phase 3) escalates into and a feeder for the Olympiad ladder (Phase 5);
with none present, the adaptive difficulty ceiling for Maths was just the
`ncertQA`/topic sets. This script adds 6 PDF-faithful boss questions per chapter
(90 total), each:

  * id in the canonical collision-free shape `bossquiz_mchNN_qII`
    (namespace token `mch` keeps Maths ids distinct from Science's
    `bossquiz_chNN_qII` — enforced by scripts/check_quiz_id_format.py and the
    SubjectRegistry global question index),
  * difficulty 3..5 (boss tier; difficulty>=3 requires non-empty solutionSteps,
    enforced by scripts/check_pack_schema.py::check_question),
  * mcq with 4 options and the answer present among them,
  * worked `solutionSteps`, >=1 `commonMistakes` note, and >=1 `variations`
    entry (prompt/answer/solutionSteps) so the kid can re-drill the idea,
  * `pageRefs` inside the chapter's real NCERT page range,
  * `source: "boss_quiz"`, `needsHumanReview: false`.

Additive only. Re-runnable (idempotent: overwrites the bossQuestions key). Writes
the canonical format `json.dumps(d, ensure_ascii=False, indent=2) + "\n"` so
verify_pack_roundtrip.py stays byte-for-byte green.
"""
import json
from pathlib import Path

PACK = Path(__file__).resolve().parent.parent / "desktopAhaan/Subjects/Packs/maths_class7.json"

PER_CHAPTER = 6


def v(prompt, answer, steps):
    """A QuestionVariation literal."""
    return {"prompt": prompt, "answer": answer, "solutionSteps": steps}


def q(prompt, options, answer, steps, mistakes, variations, difficulty, pages):
    """A boss Question literal (ids assigned in main, per-chapter)."""
    assert answer in options, f"answer {answer!r} not in options {options}"
    assert 3 <= difficulty <= 5, f"boss difficulty must be 3..5, got {difficulty}"
    assert steps, "difficulty>=3 requires non-empty solutionSteps"
    assert mistakes, "boss question must carry at least one commonMistakes note"
    assert variations, "boss question must carry at least one variation"
    return {
        "prompt": prompt,
        "questionType": "mcq",
        "options": options,
        "answer": answer,
        "solutionSteps": steps,
        "commonMistakes": mistakes,
        "variations": variations,
        "difficulty": difficulty,
        "pageRefs": pages,
        "needsHumanReview": False,
        "source": "boss_quiz",
    }


