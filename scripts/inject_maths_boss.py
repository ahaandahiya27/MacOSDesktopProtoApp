def main():
    pack = json.loads(PACK.read_text(encoding="utf-8"))

    # Map chapter id → set of its concept ids (sanity context; boss questions
    # are chapter-level, no parent anchor needed, but we keep the chapter set
    # for the lint to confirm we touch only known chapters).
    chapter_ids = {ch["id"] for ch in pack["chapters"]}
    for cid in BOSS:
        if cid not in chapter_ids:
            raise SystemExit(f"BOSS references unknown chapter {cid}")

    seen_ids = set()
    total = 0
    for ch in pack["chapters"]:
        items = BOSS.get(ch["id"])
        if not items:
            raise SystemExit(f"No bossQuestions authored for {ch['id']}")
        if len(items) < PER_CHAPTER:
            raise SystemExit(f"{ch['id']} has only {len(items)} boss questions (<{PER_CHAPTER})")
        ns = "m" + ch["id"]  # ch01 → mch01, the Maths boss-id namespace token
        built = []
        for i, it in enumerate(items):
            qid = f"bossquiz_{ns}_q{i:02d}"
            if qid in seen_ids:
                raise SystemExit(f"Duplicate boss id {qid}")
            seen_ids.add(qid)
            q_obj = {"id": qid}
            q_obj.update(it)
            built.append(q_obj)
        ch["bossQuestions"] = built
        total += len(built)

    PACK.write_text(json.dumps(pack, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Injected {total} bossQuestions across {len(pack['chapters'])} Maths chapters "
          f"({PER_CHAPTER}/chapter).")


if __name__ == "__main__":
    main()
